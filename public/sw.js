/*
 * NyAnime service worker.
 *
 * Meta requires a service worker for an installable PWA, but this app's most
 * important rules are about what NOT to touch:
 *
 * - `/api/*` is the stream proxy. Segments are large, HMAC-signed per manifest
 *   and pointless to cache; they go straight to the network.
 * - Cross-origin requests (the catalogue API, posters) are not intercepted.
 * - Hashed `/assets/*` are cache-first because their names change on deploy.
 * - Navigations are network-first so a new deploy is picked up, with the
 *   cached shell as the offline fallback.
 */
const CACHE = 'nyanime-shell-v1';
const SHELL = ['/', '/index.html', '/manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .catch(() => undefined)
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/index.html')));
    return;
  }

  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(request).then((cached) => {
        if (cached) return cached;
        return fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        });
      }),
    );
  }
});
